#!/usr/bin/env python3
"""Generate src/main.py from the @op registry (Basilisk emits the .did from it at build).

    python3 scripts/gen_main.py          # write src/main.py
    python3 scripts/gen_main.py --check  # exit 1 when it is out of date
"""

import ast
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "src"

HEAD = '''# Generated by scripts/gen_main.py from the @op registry. Do not edit.
# Stubs name each op function: Basilisk loads modules lazily, so a bare import would not register them.
import json
from typing import Tuple

from basilisk import Async, Opt, Record, StableBTreeMap, Vec, blob, ic, init, inspect_message, nat16, post_upgrade, query, text, update, void
from ic_python_db import Database

Database.init(db_storage=StableBTreeMap[str, str](memory_id=1, max_key_size=256, max_value_size=20000))

import chain  # noqa: E402
import cycles  # noqa: E402
import rounds  # noqa: E402
{imports}
from op import dispatch, run  # noqa: E402

VERSION = {{"canister": "casals_backend", "version": "VERSION_PLACEHOLDER", "sha": "COMMIT_HASH_PLACEHOLDER",
           "built_at": "BUILT_AT_ISO_PLACEHOLDER"}}
Header = Tuple[str, str]


class HttpRequest(Record):
    method: text
    url: text
    headers: Vec["Header"]
    body: blob


class HttpResponse(Record):
    status_code: nat16
    headers: Vec["Header"]
    body: blob
    streaming_strategy: Opt[text]
    upgrade: Opt[bool]


def start():
    rounds.resume({steps})
    chain.set_timer(0, cycles.refresh_subnets)


@init
def init_() -> void:
    start()


@post_upgrade
def post_upgrade_() -> void:
    start()


@inspect_message
def inspect_message_() -> void:
    if ic.method_name() == "http_request_update" or ic.caller().to_str() != chain.ANONYMOUS:
        ic.accept_message()


def version(req, upgrade):
    found = {{k: v for k, v in VERSION.items() if "PLACEHOLDER" not in v}}
    status = 200 if req["url"].split("?")[0] == "/version" else 404
    return {{"status_code": status, "headers": [("Content-Type", "application/json")],
            "body": json.dumps(found if status == 200 else {{}}).encode(), "streaming_strategy": None,
            "upgrade": upgrade if status == 200 else None}}


@query
def http_request(req: HttpRequest) -> HttpResponse:
    return version(req, True)


@update
def http_request_update(req: HttpRequest) -> HttpResponse:
    return version(req, None)


@query
def icrc10_supported_standards() -> text:
    return "[]"
'''

def registry():
    ops, modules, steps = {}, set(), []
    for path in sorted(SRC.glob("*.py")):
        for node in ast.parse(path.read_text()).body:
            for dec in getattr(node, "decorator_list", []):
                if isinstance(dec, ast.Call) and getattr(dec.func, "id", "") == "op":
                    read = any(k.arg == "read" and k.value.value for k in dec.keywords)
                    ops[node.name] = (read, path.stem)
                    modules.add(path.stem)
                if isinstance(dec, ast.Call) and getattr(dec.func, "id", "") == "step":
                    steps.append(f"{path.stem}.{node.name}")
    return dict(sorted(ops.items())), sorted(modules), steps


def render():
    ops, modules, steps = registry()
    assert {s.split(".")[0] for s in steps} <= set(modules), "a @step module must also define an @op"
    imports = "\n".join(f"import {m}  # noqa: E402" for m in modules if m not in ("cycles",))
    stubs = "\n" + "".join(
        f"@query\ndef {name}(args: text) -> text: return run(dispatch({module}.{name}, args))\n" if read else
        f"@update\ndef {name}(args: text) -> Async[text]: return (yield from dispatch({module}.{name}, args))\n"
        for name, (read, module) in ops.items())
    return HEAD.format(imports=imports, steps=", ".join(steps)) + stubs


def main():
    text, path = render(), SRC / "main.py"
    if "--check" not in sys.argv:
        path.write_text(text)
    elif not path.exists() or path.read_text() != text:
        sys.exit("src/main.py is out of date: run scripts/gen_main.py")


if __name__ == "__main__":
    main()
